const langMeta = {
  fr: { flag: '🇫🇷', label: 'Français' },
  en: { flag: '🇬🇧', label: 'English' },
  sv: { flag: '🇸🇪', label: 'Svenska' },
  es: { flag: '🇪🇸', label: 'Español' },
};

function applyLang(lang) {
  const t = translations[lang];
  if (!t) return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] === undefined) return;
    if (t[key].includes('<')) {
      el.innerHTML = t[key];
    } else {
      el.textContent = t[key];
    }
  });

  document.title = t.page_title;
  document.documentElement.lang = lang;

  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute('content', t.hero_sub);

  const btn = document.getElementById('lang-btn');
  if (btn) {
    btn.innerHTML = `${langMeta[lang].flag} ${langMeta[lang].label} <span class="lang-arrow">▾</span>`;
  }

  document.querySelectorAll('#lang-menu li').forEach(li => {
    li.classList.toggle('active', li.dataset.lang === lang);
  });

  localStorage.setItem('amplizon_lang', lang);
}

document.addEventListener('DOMContentLoaded', () => {
  const switcher = document.getElementById('lang-switcher');
  const btn = document.getElementById('lang-btn');
  const menu = document.getElementById('lang-menu');

  btn.addEventListener('click', e => {
    e.stopPropagation();
    switcher.classList.toggle('open');
  });

  document.addEventListener('click', () => {
    switcher.classList.remove('open');
  });

  menu.querySelectorAll('li').forEach(li => {
    li.addEventListener('click', e => {
      e.stopPropagation();
      applyLang(li.dataset.lang);
      switcher.classList.remove('open');
    });
  });

  const saved = localStorage.getItem('amplizon_lang') || 'fr';
  applyLang(saved);
});
