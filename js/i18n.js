const langNames = { fr: "Français", en: "English", sv: "Svenska", es: "Español" };
const langFlags = { fr: "🇫🇷", en: "🇬🇧", sv: "🇸🇪", es: "🇪🇸" };

function applyTranslation(lang) {
  const t = translations[lang];
  if (!t) return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  // Update html lang attribute
  document.documentElement.lang = lang;

  // Save preference
  localStorage.setItem('marcavio-lang', lang);

  // Update dropdown button label
  const btn = document.getElementById('lang-btn');
  if (btn) btn.innerHTML = `${langFlags[lang]} ${langNames[lang]} <span class="lang-arrow">▾</span>`;
}

function initLanguageSwitcher() {
  const saved = localStorage.getItem('marcavio-lang') || 'fr';
  applyTranslation(saved);

  const btn = document.getElementById('lang-btn');
  const dropdown = document.getElementById('lang-dropdown');

  btn.addEventListener('click', (e) => {
    e.stopPropagation();
    dropdown.classList.toggle('open');
  });

  document.addEventListener('click', () => dropdown.classList.remove('open'));

  document.querySelectorAll('[data-lang]').forEach(item => {
    item.addEventListener('click', () => {
      applyTranslation(item.getAttribute('data-lang'));
      dropdown.classList.remove('open');
    });
  });
}

document.addEventListener('DOMContentLoaded', initLanguageSwitcher);